    try:
        with open(model.COVERAGE_JSON, encoding="utf-8") as fh:
            for bench in json.load(fh):
                for t in bench.get("tests", []):
                    bins[t["test"]] = t
    except OSError:
        pass
    by_test = {}
    for r in rep["runs"]:
        by_test.setdefault(r["test"], []).append(r)
    scene = next((s for s in m["scenes"] if s["id"] == "plan:main"), None)
    order = [N[it["id"]]["name"] for it in scene["items"] if it.get("style") == "test_card"] if scene else []
    tests = [t for t in order if t in by_test] + sorted(t for t in by_test if t not in order)
    wall_min = (rep.get("wall") or 0) / 60
    failed = [r for r in rep["runs"] if not r["ok"]]

    def lab_of(n):
        if not n:
            return "—"
        if n.get("lab") == "TP":
            return "test plan"
        doc = next((d["url"] for d in n.get("docs", []) if d["title"].startswith("Lab")), None)
        return f"[{n['lab']}](../{doc})" if doc else str(n.get("lab") or "—")

    def stages_table(r):
        if not r["stages"]:
            return ["*No stage lines in this run.*", ""]
        return ["| time (ns) | stage |", "|---|---|"] + [f"| {t} | {md_cell(st)} |" for t, st in r["stages"]] + [""]

    out = ["# Regression results\n", head,
           f"[The report on GitHub →]({gh('index.md')}){{ .pm-link }}\n",
           f"**{rep['passed']} of {rep['total']} runs passed** · {rep['date']}"
           + (f" · commit `{rep['commit']}`" if rep.get("commit") else "")
           + (f" · Verilator {rep['verilator']}" if rep.get("verilator") else "")
           + f" · {wall_min:.1f} min of simulation wall time · merged functional coverage: "
           f"[Coverage results](../coverage-results.md).\n",
           "Every test of the project runs with several seeds (`scripts/regress.yaml`); the page of a test "
           "lists its seeds with the log, the timeline and the waves of each one, the stages of the test and "
           "the wave pictures of its first seed. The whole report (logs, timelines, waves) is committed in "
           f"`{rep_rel}/`; how to read a log: [Logs, timelines and waves](../appendix/sim-report.md).\n"]
    if failed:
        out += ["## Failures\n", "| Test | Seed | First error |", "|---|---|---|"]
        out += [f"| [{r['test']}]({r['test']}.md) | {r['seed']} | {md_cell(r['first_error'] or r['reason'] or 'see the log')} |"
                for r in failed] + [""]
    hist = render_history_svg()
    if hist:
        out.append(hist)
    out += ["## Tests\n", "| Test | Lab | Seeds passed | Sim time | Wall | In / fwd / drop (seed 1) | Bins hit | Page |",
            "|---|---|---|---|---|---|---|---|"]
    for t in tests:
        rs = sorted(by_test[t], key=lambda r: r["seed"])
        n = N.get(f"cls:{t}")
        ok = sum(1 for r in rs if r["ok"])
        mark = "" if ok == len(rs) else " ❌"
        times = sorted(r["sim_time"] for r in rs)
        sim = times[0] if times[0] == times[-1] else f"{times[0]}–{times[-1]}"
        wall = sum(r["wall"] or 0 for r in rs)
        c = rs[0]["counts"]
        b = bins.get(t)
        out.append(f"| `{t}` | {lab_of(n)} | {ok}/{len(rs)}{mark} | {sim} | {wall:.1f} s "
                   f"| {c['rx_in']} / {c['in_fwd']} / {c['in_drop']} | {b['bins_hit'] if b else '—'} | [{t} →]({t}.md) |")
    out.append("")
    out.append("Regenerate: `make regress ONLY=yapp_project WAVES=1 && make sim-report ONLY=yapp_project "
               "OUT=yapp_project/regression && make map`.\n")
    pages[os.path.join(REGRESSION_DIR, "index.md")] = "\n".join(out)

    for t in tests:
        rs = sorted(by_test[t], key=lambda r: r["seed"])
        n = N.get(f"cls:{t}")
        plan = (n or {}).get("plan") or {}
        first = rs[0]
        ok = sum(1 for r in rs if r["ok"])
        b = bins.get(t)
        o = [f"# {t}\n", head,
             f"[Back to the regression results →](index.md){{ .pm-link }} "
             f"[On the project map →](../project-map.md#view=plan&node=cls:{t}){{ .pm-link }}\n",
             f"**{ok} of {len(rs)} seeds passed**" + (" ❌" if ok < len(rs) else "")
             + f" · lab: {lab_of(n)}" + (f" · extends `{n['base']}`" if n and n.get("base") else "")
             + (f" · {b['bins_hit']} coverage bins hit" + (f", {len(b['only_this'])} only by this test" if b.get("only_this") else "")
                if b else "") + ".\n"]
        if plan.get("purpose"):
            o.append(md_cell(plan["purpose"]) + "\n")
        elif n and n.get("summary"):
            o.append(md_cell(n["summary"]) + "\n")
        o += ["## Seeds\n", "| Seed | Result | Sim time | Wall | In / fwd / drop | Out ch0/1/2 | Suspends | Errors | Log | Timeline | Waves |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in rs:
            c = r["counts"]
            wall = f"{r['wall']:.1f} s" if r.get("wall") is not None else "—"
            waves = (f"[Surfer ↗]({r['surfer']})" if r.get("surfer") else "") + (f" [.fst]({gh(r['fst'])})" if r.get("fst") else "")
            o.append(f"| {r['seed']} | {'pass' if r['ok'] else '**FAIL**'} | {r['sim_time']} | {wall} "
                     f"| {c['rx_in']} / {c['in_fwd']} / {c['in_drop']} | {c['out'][0]}/{c['out'][1]}/{c['out'][2]} "
                     f"| {c['suspends']} | {c['uvm_errors']} | [log ↗]({gh(r['log'])}) | [timeline ↗]({gh(r['dir'] + '/timeline.md')}) | {waves or '—'} |")
        o.append("")
        if any(not r["ok"] for r in rs):
            o += ["### First error of each failed seed\n"]
            o += [f"- seed {r['seed']}: `{md_cell(r['first_error'] or r['reason'] or 'see the log')}`" for r in rs if not r["ok"]] + [""]
        if plan.get("stages"):
            o += ["## The plan of the test\n"]
            o += [f"{i + 1}. **{md_cell(st.get('t', ''))}**" + (f" — {md_cell(st['d'])}" if st.get("d") else "")
                  for i, st in enumerate(plan["stages"])] + [""]
            if plan.get("expected"):
                o += ["Expected:\n"] + [f"- {x}" for x in plan["expected"]] + [""]
        covers = (n or {}).get("covers") or []
        if covers:
            o += ["## Test plan items this test verifies\n"]
            for c in covers:
                g = N[c["group"]]
                anchor = re.sub(r"[^a-z0-9 -]", "", f"{g['type']} - {g['name']}".lower()).replace(" ", "-")
                o.append(f"- [{c['id']}](../test-plan.md#{anchor}) — {md_cell(c['title'])} ({c['status']})")
            o.append("")
        o += [f"## Seed {first['seed']}: what happened\n"] + first["summary"] + [""]
        o += [f"### Stages\n"] + stages_table(first)
        if first.get("pictures"):
            o += ["### Pictures\n", "The moments the report draws from the signal trace of this run "
                  "(the same pictures are in the run's folder of the report).\n"]
            for name, title in first["pictures"]:
                o += [f"**{md_cell(title)}**\n", f"![{md_cell(title)}](../assets/regression/{t}/{name})\n"]
        o.append(f"Run it yourself: `make sim TEST={t} SEED={first['seed']} WAVES=1` in `yapp_project/tb`, or "
                 f"`make run-project TEST={t}` with Xcelium.\n")
