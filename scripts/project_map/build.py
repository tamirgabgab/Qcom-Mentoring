#!/usr/bin/env python3
"""
build.py -- generate the project map.

    python3 -m scripts.project_map.build            # model.json + standalone HTML
    python3 -m scripts.project_map.build --check    # also run the consistency checks (test_model.py,
                                                    # test_sim.mjs with node) and fail if the
                                                    # committed files are out of date

Outputs (committed, so the site and the offline file never need pyslang):
    docs/assets/project_map/model.json
    docs/assets/project_map/regmap.js      (the register map of regmap.yaml, for sim.js)
    docs/downloads/yapp_project_map.html
    docs/test-plan.md                      (the feature matrix and the tests of annotations.yaml plan: / tests:)
    docs/coverage-results.md               (the merged functional coverage of yapp_project/regression/coverage.json)
    docs/dut/register-map.md               (the register map of regmap.yaml as a plain Markdown page)
"""
